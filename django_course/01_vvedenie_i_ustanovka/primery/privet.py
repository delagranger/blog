# --- Функции ---------------------------------------------------------------
# Функция — это блок кода с именем. Её можно вызывать много раз.
# В Django мы часто пишем функции-представления (views) — с ними
# познакомимся в уроке 3.


def skazhi_privet(imya):
    """Возвращает строку с приветствием."""
    return f"Привет, {imya}!"


# --- Списки и циклы --------------------------------------------------------
# Список — это набор элементов. В Django списки возвращаются из базы данных
# в виде набора записей (QuerySet).

ucheniki = ["Аня", "Борис", "Вера"]

print("Цикл for по списку:")
for imya in ucheniki:
    print(" ", skazhi_privet(imya))

# --- Условия ----------------------------------------------------------------
# Условие if позволяет выполнять код только когда что-то истинно.
# В шаблонах Django тоже есть условия, но с другим синтаксисом (урок 6).

vozrast = 20
if vozrast >= 18:
    print("\nТебе можно регистрироваться на сайте.")
else:
    print("\nТебе ещё рано регистрироваться.")

# --- Словари ----------------------------------------------------------------
# Словарь хранит пары «ключ -> значение».
# В Django словарь часто называют «контекстом» — именно через него
# данные передаются из view в шаблон.

polzovatel = {
    "imya": "Аня",
    "vozrast": 20,
    "gorod": "Москва",
}

print("\nСловарь (будущий контекст шаблона):")
# .items() возвращает пары ключ-значение, которые удобно перебирать в цикле.
for klyuch, znachenie in polzovatel.items():
    print(f"  {klyuch}: {znachenie}")

# --- Классы -----------------------------------------------------------------
# Класс — это «чертёж» для создания объектов.
# Модели Django — это классы (познакомимся в уроке 4).


class Post:
    """Модель поста в блоге (упрощённая)."""

    def __init__(self, zagolovok, tekst):
        self.zagolovok = zagolovok
        self.tekst = tekst

    def korotko(self):
        """Возвращает первые 20 символов текста."""
        return self.tekst[:20] + "..."


post = Post("Мой первый пост", "Сегодня я начал изучать Django.")
print("\nОбъект класса Post:")
print("  Заголовок:", post.zagolovok)
print("  Анонс:", post.korotko())